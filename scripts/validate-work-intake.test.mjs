import test from 'node:test';
import assert from 'node:assert/strict';
import {validateWorkIntake as validate} from './validate-work-intake.mjs';
const pr={number:172,state:'open',body:'Refs #14\nReuses: src/baseline/product-capability.mjs'};
const issues=[{number:14,state:'open'}];
/* Deep-copy issue rows — hostile tests mutate state and must not poison later cases. */
const args=()=>({pr:{...pr},issues:issues.map((i)=>({...i})),openPrs:[],lookupComplete:true});
test('current open canonical issue and reuse qualifies',()=>{assert.equal(validate(args()).ok,true)});
const hostile=(name,edit,code)=>test(name,()=>{const a=args();edit(a);const r=validate(a);assert.equal(r.ok,false);assert.ok(r.errors.some(x=>x.startsWith(code)),JSON.stringify(r))});
hostile('missing refs',a=>a.pr.body='Reuses: current','EXACT_ONE_OPEN_ISSUE_REF_REQUIRED');
hostile('two refs',a=>a.pr.body+='\nRefs #12','EXACT_ONE_OPEN_ISSUE_REF_REQUIRED');
hostile('issue closed',a=>a.issues[0].state='closed','REFERENCED_ISSUE_NOT_OPEN');
hostile('issue absent',a=>a.issues=[],'REFERENCED_ISSUE_NOT_OPEN');
hostile('issue number is PR',a=>a.issues[0].pull_request={url:'x'},'REFERENCED_ISSUE_NOT_OPEN');
hostile('duplicate open PR',a=>a.openPrs=[{number:171,state:'open',body:'Refs #14'}],'EXTEND_EXISTING_PR');
hostile('does not self collide',a=>{a.openPrs=[{...a.pr}];a.issues[0].state='closed'},'REFERENCED_ISSUE_NOT_OPEN');
hostile('no existing tool reuse',a=>a.pr.body='Refs #14','REUSE_OR_TWO_SEARCHES_REQUIRED');
hostile('new because alone',a=>a.pr.body='Refs #14\nNew because: no existing tool','REUSE_OR_TWO_SEARCHES_REQUIRED');
test('new because with two searches allowed',()=>{const a=args();a.pr.body='Refs #14\nNew because: both sources empty\nSearch 1: SDK\nSearch 2: framework';assert.equal(validate(a).ok,true)});
hostile('one search insufficient',a=>a.pr.body='Refs #14\nNew because: missing\nSearch 1: sdk','REUSE_OR_TWO_SEARCHES_REQUIRED');
hostile('provider listing incomplete',a=>a.lookupComplete=false,'PROVIDER_LOOKUP_INCOMPLETE');
hostile('missing PR identity',a=>a.pr.number=null,'PR_ID_MISSING');
test('result grants no authority',()=>{assert.equal(validate(args()).authority,'NONE')});
