import assert from 'node:assert/strict';
import {harvestOccurrences,resolveResume} from '../src/continuity/flap-harvest.mjs';
import {createHash} from 'node:crypto';
const body=Buffer.alloc(28224,0x42), digest=createHash('sha256').update(body).digest('hex');
let n=0;const check=v=>{assert.ok(v);n++};
const input=Array.from({length:10},(_,i)=>({occurrence_ref:`occurrence:${i}`,generation:'g1',bytes:body}));
const h=harvestOccurrences(input,{generation:'g1',source_ref:'browser:session'});
check(h.received===10&&h.unique===1&&h.redundant===9);
check(h.payloads[0].occurrence_refs.length===10 && h.payloads[0].byte_length===28224);
check(h.payloads[0].content_sha256===digest);
check(h.provider_effect===false);
assert.throws(()=>harvestOccurrences([input[0],input[0]],{generation:'g1',source_ref:'browser:session'}));n++;
assert.throws(()=>harvestOccurrences([{...input[0],generation:'g2'}],{generation:'g1',source_ref:'browser:session'}));n++;
const base={source_ref:'browser:session',generation:'g1',content_sha256:digest,cursor:12,acknowledged_cursor:11};
check(resolveResume(base).state==='ELIGIBLE_FOR_SEPARATE_ADMISSION');
const effect_receipt={...base,committed_digest:'commit:d1',receipt_ref:'receipt:r1'};
check(resolveResume({...base,effect_receipt}).state==='READBACK_REQUIRED');
check(resolveResume({...base,effect_receipt,readback:{...base,committed_digest:'commit:d1'}}).state==='RECOVER_EXISTING_EFFECT');
check(resolveResume({...base,effect_receipt,readback:{...base,committed_digest:'commit:d2'}}).state==='RED_READBACK_MISMATCH');
check(resolveResume({...base,acknowledged_cursor:12}).state==='ACKED');
check(resolveResume({...base,effect_receipt:{...effect_receipt,generation:'g2'}}).state==='RED_RECEIPT_DRIFT');
console.log(JSON.stringify({checks:n,passed:n,failed:0,quantize:'10-to-1 synthetic fixture',interrupted_post_commit_pre_ack:'RECOVER_EXISTING_EFFECT',repeat_effect:false,provider_effect:false}));
